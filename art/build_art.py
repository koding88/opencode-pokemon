"""Turns a cut-out PNG into half-block cells for the plugin: writes src/cr7-art.js.

usage: python3 art/build_art.py art/siuu_cut.png --width 22
Each row is a list of [text, fg, bg] segments; fg/bg are "#rrggbb" or null (transparent).
"""
import json
import sys
from pathlib import Path
from PIL import Image

src = sys.argv[1]
width = int(sys.argv[sys.argv.index("--width") + 1]) if "--width" in sys.argv else 22

img = Image.open(src).convert("RGBA")
img = img.crop(img.getchannel("A").point(lambda v: 255 if v >= 128 else 0).getbbox())
height = max(2, round(img.height * width / img.width / 2) * 2)
small = img.resize((width, height), Image.LANCZOS)

hexc = lambda p: "#%02x%02x%02x" % p[:3]
rows = []
for y in range(0, height, 2):
    segments = []
    for x in range(width):
        top, bottom = small.getpixel((x, y)), small.getpixel((x, y + 1))
        t, b = top[3] >= 128, bottom[3] >= 128
        if t and b:
            cell = ["▀", hexc(top), hexc(bottom)]
        elif t:
            cell = ["▀", hexc(top), None]
        elif b:
            cell = ["▄", hexc(bottom), None]
        else:
            cell = [" ", None, None]
        last = segments[-1] if segments else None
        if last and last[1] == cell[1] and last[2] == cell[2]:
            last[0] += cell[0]
        else:
            segments.append(cell)
    rows.append(segments)

out = Path(__file__).resolve().parent.parent / "src" / "cr7-art.js"
out.write_text(
    "// Generated by art/build_art.py from a Wikimedia Commons photo (CC BY-SA 4.0):\n"
    "// https://commons.wikimedia.org/wiki/File:Cristiano_Ronaldo_0876.jpg\n"
    f"export const SIUU_WIDTH = {width};\n"
    f"export const SIUU = {json.dumps(rows, ensure_ascii=False)};\n"
)
print(f"wrote {out} ({width}x{len(rows)})")
